from dataclasses import dataclass


@dataclass
class NetworkInput:
    """
    Represents the network conditions and characteristics
    used by the Multi-Factor Decision Engine.
    """

    traffic_type: str
    threat_level: float
    congestion: float
    bandwidth_available: float
    application_priority: float
    device_trust: float
    latency: float

    def validate(self) -> None:
        """Validate all input values before processing."""

        if not 0 <= self.threat_level <= 10:
            raise ValueError("Threat level must be between 0 and 10.")

        if not 0 <= self.congestion <= 10:
            raise ValueError("Congestion must be between 0 and 10.")

        if self.bandwidth_available < 0:
            raise ValueError("Available bandwidth cannot be negative.")

        if not 0 <= self.application_priority <= 10:
            raise ValueError(
                "Application priority must be between 0 and 10."
            )

        if not 0 <= self.device_trust <= 100:
            raise ValueError(
                "Device trust score must be between 0 and 100."
            )

        if self.latency < 0:
            raise ValueError("Latency cannot be negative.")


@dataclass
class DecisionResult:
    """
    Output generated by the Multi-Factor Decision Engine.
    """

    decision_score: float
    priority: str
    qos_policy: str
    bandwidth_allocation: float
    queue: str
    security_action: str
    reason: str